#!/usr/bin/env bash
# Write a local .env for `make dev` from an OpenStack credentials file
# (default ./test-cred, lines of `export OS_*=...`). Never commits secrets:
# .env is git-ignored. Re-running keeps an existing HIVE_SECRET_KEY.
set -euo pipefail

cred="${1:-test-cred}"
if [ ! -f "$cred" ]; then
  echo "credentials file not found: $cred" >&2
  exit 1
fi
# shellcheck disable=SC1090
source "$cred"

auth_url="${OS_AUTH_URL%/}"
case "$auth_url" in */v3) ;; *) auth_url="$auth_url/v3" ;; esac

secret=""
if [ -f .env ]; then
  secret="$(grep -E '^HIVE_SECRET_KEY=' .env | head -1 | cut -d= -f2- || true)"
fi
if [ -z "$secret" ]; then
  secret="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
fi

host="${auth_url#https://}"; host="${host%%/*}"
case "$host" in
  identity.rctest.nectar.org.au) accounts="https://accounts.test.rc.nectar.org.au"; dash="https://dashboard.rctest.nectar.org.au"; status="https://status.rctest.nectar.org.au" ;;
  *) accounts="https://accounts.rc.nectar.org.au"; dash="https://dashboard.rc.nectar.org.au"; status="https://status.rc.nectar.org.au" ;;
esac

cat > .env <<EOF
# Generated by scripts/make-env.sh from $cred on $(date -u +%Y-%m-%dT%H:%M:%SZ)
HIVE_ENV=dev
HIVE_PUBLIC_URL=http://localhost:5173
HIVE_COOKIE_SECURE=false
HIVE_DOCS_ENABLED=true
HIVE_LOG_FORMAT=console
HIVE_KEYSTONE_URL=$auth_url
HIVE_REGION=Melbourne
HIVE_LOGIN_URL=$accounts/login
HIVE_LOGIN_URL_NZ=$accounts/Shibboleth.sso/DS-Tuakiri?return-path=/login/
HIVE_WEBSSO_ALLOWED_ORIGINS=$accounts,http://127.0.0.1:8765,http://localhost:8765
HIVE_REDIS_URL=redis://localhost:6379/0
HIVE_SECRET_KEY=$secret
HIVE_HORIZON_URL=$dash
HIVE_ALLOCATION_API_URL=$dash/rest_api
HIVE_OUTAGE_BASE_URL=$status/outages/
EOF
echo "wrote .env for $auth_url"
