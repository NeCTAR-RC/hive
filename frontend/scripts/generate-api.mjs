#!/usr/bin/env node
// The SPA's API contract, generated from the backend: the OpenAPI document
// (`src/lib/api/generated/openapi.json`, exported by
// `backend/scripts/export_openapi.py`) and the TypeScript types built from
// it by openapi-typescript (`src/lib/api/generated/openapi.d.ts`). Both are
// committed; the domain modules in `src/lib/api/types/` alias the types and
// the mocks' contract test validates replies against the document.
//
//   node scripts/generate-api.mjs           export the document, write both files
//   node scripts/generate-api.mjs --check   fail when either file is stale
//
// The export needs a Python with the backend's dependencies: HIVE_PYTHON,
// else the first backend virtualenv found (the ones `make start` uses),
// else `python3`. `--check` (run by `pnpm lint`) skips the export half with
// a notice when HIVE_PYTHON is unset and no backend virtualenv exists, so a
// frontend-only run still checks the types against the committed document.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const REPO = fileURLToPath(new URL("../../", import.meta.url));
const DOCUMENT = fileURLToPath(
  new URL("../src/lib/api/generated/openapi.json", import.meta.url),
);
const TYPES = fileURLToPath(
  new URL("../src/lib/api/generated/openapi.d.ts", import.meta.url),
);
const EXPORT_SCRIPT = `${REPO}backend/scripts/export_openapi.py`;
const BACKEND_VENVS = [".tox/dev", ".tox/py314", ".tox/py312", ".venv"];
const HEADER = `/**
 * Generated by \`pnpm generate:api\` from openapi.json (the backend's
 * OpenAPI document) with openapi-typescript. Do not edit by hand.
 */

`;

/** The Python to export with: HIVE_PYTHON, else a backend venv, else null. */
function backendPython() {
  if (process.env.HIVE_PYTHON) return process.env.HIVE_PYTHON;
  const venv = BACKEND_VENVS.map((dir) => `${REPO}${dir}/bin/python`).find(
    (python) => existsSync(python),
  );
  return venv ?? null;
}

/**
 * The backend's OpenAPI document as text. PYTHONPATH points at this
 * checkout's `backend/`, so the export reads these routes and models even
 * when the Python has another checkout of hive installed.
 */
function exportDocument(python) {
  const result = spawnSync(python, [EXPORT_SCRIPT], {
    encoding: "utf8",
    env: { ...process.env, PYTHONPATH: `${REPO}backend` },
  });
  if (result.status !== 0) {
    console.error(result.error?.message ?? result.stderr);
    console.error(
      `Exporting the OpenAPI document with ${python} failed; set HIVE_PYTHON ` +
        "to a Python with the backend's dependencies (pip install -e .).",
    );
    process.exit(1);
  }
  return result.stdout;
}

/**
 * The TypeScript types for a document, with the generated-file header. A
 * field with a default stays optional: in the document only request models
 * carry defaults, and a request may leave such a field out.
 */
async function typesFor(documentText) {
  const ast = await openapiTS(JSON.parse(documentText), {
    defaultNonNullable: false,
    silent: true,
  });
  return HEADER + astToString(ast);
}

/** Whether a committed file matches the expected text; reports it if not. */
function isCurrent(path, expected) {
  const committed = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (committed === expected) return true;
  console.error(`${path} is stale; run \`pnpm generate:api\`.`);
  return false;
}

const mode = process.argv[2];
if (mode === undefined) {
  const document = exportDocument(backendPython() ?? "python3");
  writeFileSync(DOCUMENT, document);
  writeFileSync(TYPES, await typesFor(document));
  console.log("Wrote src/lib/api/generated/openapi.{json,d.ts}.");
} else if (mode === "--check") {
  const python = backendPython();
  let current = true;
  if (python === null) {
    console.log(
      "generate:api --check: HIVE_PYTHON is unset and no backend virtualenv " +
        `(${BACKEND_VENVS.join(", ")}) exists, so the OpenAPI document is ` +
        "not compared with the backend; the types are checked against the " +
        "committed document only.",
    );
  } else {
    current = isCurrent(DOCUMENT, exportDocument(python));
  }
  const document = readFileSync(DOCUMENT, "utf8");
  current = isCurrent(TYPES, await typesFor(document)) && current;
  if (!current) process.exit(1);
} else {
  console.error(`Unknown option ${mode}; use --check or no option.`);
  process.exit(2);
}
